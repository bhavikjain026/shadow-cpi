def render(template, values):
    missing = sorted({k for k in PLACEHOLDER.findall(template) if k not in values})
    if missing:
        raise SystemExit(f"template uses keys facts() does not provide: {', '.join(missing)}")
    return PLACEHOLDER.sub(lambda m: values[m.group(1)], template)


def render_block(doc, tmpl, body):
    """`doc` with the text between its BLOCK_START and BLOCK_END marker lines replaced by `body`."""
    start, end = BLOCK_START.format(tmpl=tmpl), BLOCK_END
    if doc.count(start) != 1 or doc.count(end) != 1 or doc.index(start) > doc.index(end):
        raise SystemExit(f"generated-block markers for {tmpl} missing or out of order")
    head, rest = doc.split(start, 1)
    # blank lines around the body, so a table at its end closes before the end marker
    return head + start + "\n\n" + body.strip("\n") + "\n\n" + end + rest.split(end, 1)[1]


def sync(st, as_of, root=ROOT, write=True, values=None):
    """Render every template and generated block; returns the files that changed."""
    values = facts(st, as_of, root) if values is None else values
    changed = []
    outputs = {out: GENERATED.format(tmpl=tmpl) + render((root / tmpl).read_text(encoding="utf-8"), values)
               for out, tmpl in TEMPLATES.items()}
    for out, tmpl in BLOCKS.items():
        outputs[out] = render_block((root / out).read_text(encoding="utf-8"), tmpl,
                                    render((root / tmpl).read_text(encoding="utf-8"), values))
    for out, text in outputs.items():
        p = root / out
        if not p.exists() or p.read_text(encoding="utf-8") != text:
            changed.append(out)
            if write:
                p.parent.mkdir(parents=True, exist_ok=True)
                p.write_text(text, encoding="utf-8")
    return changed


def main(argv):
    as_of = date.fromisoformat(argv[argv.index("--as-of") + 1]) if "--as-of" in argv else date.today()
    st = run_stats()
    if not st["total"] or st["median_latency_s"] is None:
        raise SystemExit("no uncached Tavily calls in the flight recorder; nothing to sync")
    changed = sync(st, as_of, write="--check" not in argv)
    print(f"as of {as_of}: {st['calls']} calls, {st['credits']} credits, {st['inside']} of {st['total']} inside the "
          f"window, median {st['median_latency_s']:.1f} s; " + (f"changed: {', '.join(changed)}" if changed
                                                                  else "docs already match"))
    if "--check" in argv and changed:
        sys.exit(1)


