#!/usr/bin/env python3
"""Render README.md and docs/devpost_draft.md from their templates, with every number read from the results files.

    python tools/sync_doc_numbers.py                 # as of today (0 credits)
    python tools/sync_doc_numbers.py --as-of 2026-10-25
    python tools/sync_doc_numbers.py --check         # exit 1 if a doc would change; writes nothing

The prose lives in docs/templates/README.md and docs/templates/devpost.md, which hold no typed numbers: each number is
a {{key}} placeholder filled by facts() below from a committed results file (or, for the run-dependent counts, from
tools/prompt_t.py run_stats, labelled "as of <date>"). The only numbers not from our own results are two facts about
other people's work (a paper's leak rate, MoSPI's release hour), kept with their sources in config/doc_citations.json.
Edit the templates, never the rendered files; tests/test_sync_doc_numbers.py fails if a template types a digit.
"""
import ast
import csv
import json
import re
import subprocess
import sys
from datetime import date, timedelta
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "tools"))
from prompt_t import run_stats  # noqa: E402

TEMPLATES = {"README.md": "docs/templates/README.md", "docs/devpost_draft.md": "docs/templates/devpost.md"}
PLACEHOLDER = re.compile(r"\{\{\s*([a-z0-9_]+)\s*\}\}")
GENERATED = "<!-- Generated by tools/sync_doc_numbers.py from {tmpl}: edit the template, not this file. -->\n"


def human(d):
    return f"{d.day} {d:%b} {d.year}"


def day_month(d):
    return f"{d.day} {d:%b}"


def load(rel, root=ROOT):
    return json.loads((root / rel).read_text(encoding="utf-8"))


def pp(x):
    return f"{x:.3f}"


def pct(x):
    return f"{x:.0%}"


def secs(x):
    return f"{x:.1f} s"


def credits_per_call(x):
    return "n/a" if x is None else f"{x:.2f}"


def leakage_table(fr):
    """The field report's leakage rows (results/field_report.json), one line per check and setting."""
    out = ["| Check | Setting | Leaked, before retry | Leaked, after the logged archive retry | Valid evidence kept "
           "(before retry) | Credits per call | Median latency |", "|---|---|---|---|---|---|---|"]
    rows = fr["leakage"]["rows"]
    keyed = {}
    for r in rows:
        keyed.setdefault((r["check"], r["setting"]), {})[r["run"]] = r
    for (check, setting), runs in keyed.items():
        a = runs.get("first pass") or next(iter(runs.values()))
        b = runs.get("after logged retry")

        def leaks(r):
            return "—" if r is None or r["leaks"] is None else f"{r['leaks']} of {r['n']}"

        kept = "—" if a["valid_kept"] is None else f"{a['valid_kept']} of {a['valid_total']}"
        lat = "—" if a["median_latency_s"] is None else secs(a["median_latency_s"])
        out.append(f"| {check} | {setting} | {leaks(a)} | {leaks(b) if b else '—'} | {kept} "
                   f"| {credits_per_call(a['credits_per_call'])} | {lat} |")
    return "\n".join(out)


def nemotron_calls(root=ROOT):
    """Calls sent to Token Factory per model, and the total including cache hits (flight recorder)."""
    sent, total = {}, {}
    for line in (root / "results/app/flight_recorder.jsonl").read_text(encoding="utf-8").splitlines():
        e = json.loads(line)
        if e.get("service") != "nebius":
            continue
        m = e["params"].get("model")
        total[m] = total.get(m, 0) + 1
        if not e.get("cached"):
            sent[m] = sent.get(m, 0) + 1
    return sent, total


def quote_tally(root=ROOT):
    """'Our tally: 10 verbatim (...), 1 paywalled, 0 unreachable, 1 not checked' from audit/quote_check.md."""
    s = (root / "audit/quote_check.md").read_text(encoding="utf-8")
    m = re.search(r"Our tally: (\d+) verbatim .*?, (\d+) paywalled, (\d+) unreachable, (\d+) not checked", s)
    if not m:
        raise SystemExit("audit/quote_check.md: tally line not found")
    return dict(zip(("verbatim", "paywalled", "unreachable", "not_checked"), map(int, m.groups())))


def seal_date(root=ROOT):
    """SEAL_DATE in app_pages/common.py (read as text: importing it would start Streamlit)."""
    m = re.search(r"^SEAL_DATE = date\((\d+), (\d+), (\d+)\)", (root / "app_pages/common.py").read_text(), re.M)
    return date(*map(int, m.groups()))


def earliest_commit(root=ROOT):
    shallow = subprocess.run(["git", "rev-parse", "--is-shallow-repository"], cwd=root, capture_output=True,
                             text=True, check=True).stdout.strip()
    if shallow == "true":
        raise SystemExit("shallow clone: the earliest commit is not visible; run `git fetch --unshallow` first")
    out = subprocess.run(["git", "log", "--reverse", "--format=%ad", "--date=short"], cwd=root,
                         capture_output=True, text=True, check=True).stdout.split()
    return date.fromisoformat(out[0])


def facts(st, as_of, root=ROOT):
    """Every {{key}} the templates use, as display strings. Source file named on each block."""
    from build_bug_reports import date_lag, map_zero
    from build_field_report import check_e_dates
    from shadow_cpi.polls import release_date
    f = {}

