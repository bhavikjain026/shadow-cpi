#!/usr/bin/env python3
"""Retry reconciliation (Field Report, linked from the README): every case whose label changed after the logged
Wayback retry, with its label before and after and the reason. Offline, 0 calls.

    python tools/build_retry_table.py

Read from results/leak_demo.json (per-result labels on the first pass and after the retry, built from the date test,
the finance check and their retry files) and the retry files' recovered captures. A case's label is "confirmed leak"
if any of its results is a Wayback-confirmed leak, else "no confirmed leak". Writes results/retry_reconciliation.json
and docs/retry_reconciliation.md (generated; do not edit by hand).
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "results" / "retry_reconciliation.json"
DOC = ROOT / "docs" / "retry_reconciliation.md"
RETRY = {"date": "results/date_field_test_wayback_retry.json", "finance": "results/finance_lookahead_wayback_retry.json"}
SIDES = {"open": "no time lock", "locked": "Tavily time lock"}
LEAK = "confirmed leak (Wayback)"


def load(rel):
    return json.loads((ROOT / rel).read_text(encoding="utf-8"))


def case_label(results, key):
    return "confirmed leak" if any(r[key] == LEAK for r in results) else "no confirmed leak"


def build():
    demo = load("results/leak_demo.json")
    got = {t: load(f)["recovered_captures"] for t, f in RETRY.items()}
    rows = []
    for c in demo["cases"]:
        for side, name in SIDES.items():
            res = c[side]["results"]
            before, after = case_label(res, "label_first_pass"), case_label(res, "label")
            if before == after:
                continue
            why = []
            for r in res:
                if r["label"] != r["label_first_pass"]:
                    caps = got[c["test"]].get(r["url"]) or []
                    first = min(caps) if caps else "none"
                    why.append(f"{r['url']}: archive lookup failed on the initial pass (network); the retry found the "
                               f"first Wayback capture on {first} (cutoff {c['cutoff']}), so {r['label_first_pass']} "
                               f"→ {r['label']}")
            rows.append({"case": c["id"], "test": c["test_name"], "item": c["name"], "search": name,
                         "cutoff": c["cutoff"], "before": before, "after": after, "reasons": why})
    retry = {t: {k: load(f)[k] for k in ("run_utc", "rule", "failed_urls", "recovered", "still_failed")}
             for t, f in RETRY.items()}
    return {"note": "cases whose label changed after the logged Wayback retry; the initial pass stays the "
                    "pre-registered result", "source": "results/leak_demo.json + the two retry files",
            "retry_runs": retry, "changed": len(rows), "cases": len(demo["cases"]), "rows": rows}


def markdown(t):
    out = ["# Retry reconciliation", "",
           "<!-- Generated by tools/build_retry_table.py from results/retry_reconciliation.json: do not edit. -->", "",
           f"Every case whose label changed after the logged Wayback retry: {t['changed']} of {t['cases']} cases. The "
           "retry only repeated archive lookups that had failed on the network (same query, same labels); the initial "
           "pass stays the pre-registered result. Source: `results/retry_reconciliation.json`.", "",
           "| Case | Test | Item | Search | Before | After | Reason |", "|---|---|---|---|---|---|---|"]
    for r in t["rows"]:
        out.append(f"| {r['case']} | {r['test']} | {r['item']} | {r['search']} | {r['before']} | {r['after']} | "
                   + "<br>".join(x.replace("|", "\\|") for x in r["reasons"]) + " |")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    t = build()
    OUT.write_text(json.dumps(t, ensure_ascii=False, indent=1), encoding="utf-8")
    DOC.write_text(markdown(t), encoding="utf-8")
    print(f"{t['changed']} of {t['cases']} cases changed label after the retry")
